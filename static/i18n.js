const LANGS = ['ru', 'uz', 'en', 'qq'];
const LANG_NAMES = { ru: 'Русский', uz: "O'zbekcha", en: 'English', qq: 'Qaraqalpaqsha' };
const detectLang = () => { const n = (navigator.language || 'ru').slice(0, 2); return ['ru', 'uz', 'en'].includes(n) ? n : 'ru'; };
let lang = LANGS.includes(localStorage.lang) ? localStorage.lang : detectLang();
const t = k => { const a = D[k]; return a ? (a[LANGS.indexOf(lang)] || a[0]) : k; };
function setLang(l) { if (LANGS.includes(l)) { lang = l; localStorage.lang = l; } }
// применить язык ко всем элементам с data-i18n / data-ph / data-aria на странице
function applyI18n(root = document) {
  document.documentElement.lang = lang === 'qq' ? 'kaa' : lang;
  root.querySelectorAll('[data-i18n]').forEach(e => e.textContent = t(e.dataset.i18n));
  root.querySelectorAll('[data-ph]').forEach(e => e.placeholder = t(e.dataset.ph));
  root.querySelectorAll('[data-aria]').forEach(e => e.setAttribute('aria-label', t(e.dataset.aria)));
}
// кнопки выбора языка: <div data-langsw></div>
function mountLangSwitch(root = document, onChange) {
  root.querySelectorAll('[data-langsw]').forEach(el => {
    el.innerHTML = LANGS.map(l => `<button type="button" data-l="${l}" title="${LANG_NAMES[l]}" class="${l === lang ? 'on' : ''}" aria-pressed="${l === lang}">${l === 'qq' ? 'QQ' : l.toUpperCase()}</button>`).join('');
    el.onclick = e => { const b = e.target.closest('[data-l]'); if (!b) return; setLang(b.dataset.l); localStorage.langPick = '1'; mountLangSwitch(root, onChange); applyI18n(); onChange && onChange(b.dataset.l); };
  });
}

